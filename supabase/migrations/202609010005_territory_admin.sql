create table if not exists public.pulso_localidades (
  id bigint generated by default as identity primary key,
  cidade_id bigint not null references public.pulso_cidades(id),
  nome text not null,
  tipo text not null check (tipo in ('Bairro','Distrito','Povoado','Zona rural','Outra')),
  created_at timestamptz not null default now(),
  unique (cidade_id, nome, tipo)
);

alter table public.pulso_localidades enable row level security;
grant select on public.pulso_localidades to anon, authenticated;
revoke insert, update, delete on public.pulso_localidades from anon, authenticated;
drop policy if exists pulso_localidades_leitura on public.pulso_localidades;
create policy pulso_localidades_leitura on public.pulso_localidades
for select to anon, authenticated using (true);

create or replace function public.pulso_admin_add_street(
  p_token text, p_nome text, p_cep text default null, p_distrito text default null,
  p_bairro text default null, p_loteamento text default null,
  p_latitude double precision default null, p_longitude double precision default null
) returns public.pulso_ruas
language plpgsql security definer set search_path=public,extensions as $$
declare v_row public.pulso_ruas;
begin
  if not exists(select 1 from pulso_sessions where token_hash=encode(digest(p_token,'sha256'),'hex') and expires_at>now()) then raise exception 'unauthorized'; end if;
  if nullif(trim(p_nome),'') is null then raise exception 'nome obrigatório'; end if;
  perform pg_advisory_xact_lock(72682501);
  insert into pulso_ruas(id,cidade_id,nome,cep,distrito,bairro,loteamento,latitude,longitude)
  values(coalesce((select max(id)+1 from pulso_ruas),1),1,trim(p_nome),nullif(trim(p_cep),''),nullif(trim(p_distrito),''),nullif(trim(p_bairro),''),nullif(trim(p_loteamento),''),p_latitude,p_longitude)
  returning * into v_row;
  return v_row;
end $$;

create or replace function public.pulso_admin_add_locality(
  p_token text, p_nome text, p_tipo text
) returns public.pulso_localidades
language plpgsql security definer set search_path=public,extensions as $$
declare v_row public.pulso_localidades;
begin
  if not exists(select 1 from pulso_sessions where token_hash=encode(digest(p_token,'sha256'),'hex') and expires_at>now()) then raise exception 'unauthorized'; end if;
  if nullif(trim(p_nome),'') is null then raise exception 'nome obrigatório'; end if;
  insert into pulso_localidades(cidade_id,nome,tipo) values(1,trim(p_nome),p_tipo) returning * into v_row;
  return v_row;
end $$;

grant execute on function public.pulso_admin_add_street(text,text,text,text,text,text,double precision,double precision) to anon,authenticated;
grant execute on function public.pulso_admin_add_locality(text,text,text) to anon,authenticated;
